// Generates mobile assets from sources already in the repo:
//  - round flags (circle-flags, MIT) → assets/flags/<iso2>.png + src/lib/flags.generated.ts
//  - Higgsfield imagery (apps/web/public/media, 1200w webp) → assets/media/*.webp at 900w
//  - app icon, adaptive icon and splash from the BLEUSIM "Orbit" symbol
// Western Sahara (EH) has no flag here: it is part of Morocco on every BLEUSIM surface.
import sharp from "sharp";
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const countries = JSON.parse(readFileSync(join(root, "../../packages/geospatial/data/countries.json"), "utf8"));
const flagsDir = join(dirname(require.resolve("circle-flags/package.json")), "flags");
const webMedia = join(root, "../web/public/media");

mkdirSync(join(root, "assets/flags"), { recursive: true });
mkdirSync(join(root, "assets/media"), { recursive: true });

// 1. Flags
const isos = [...new Set(countries.map((c) => c.iso2).filter((x) => x && x !== "EH").map((x) => x.toLowerCase()))].sort();
const have = [];
for (const iso of isos) {
  const src = join(flagsDir, `${iso}.svg`);
  if (!existsSync(src)) { console.warn("no flag", iso); continue; }
  await sharp(readFileSync(src), { density: 300 }).resize(120, 120).png({ compressionLevel: 9, palette: true }).toFile(join(root, `assets/flags/${iso}.png`));
  have.push(iso);
}
writeFileSync(join(root, "src/lib/flags.generated.ts"),
  "// Generated by scripts/prepare-assets.mjs. Do not edit.\n/* eslint-disable */\nexport const FLAGS: Record<string, number> = {\n" +
  have.map((i) => `  ${i.toUpperCase()}: require("../../assets/flags/${i}.png"),`).join("\n") + "\n};\n");

// 2. Imagery
const media = {};
const add = async (name, file, w = 900) => {
  const src = join(webMedia, file);
  if (!existsSync(src)) return console.warn("missing", file);
  await sharp(src).resize({ width: w }).webp({ quality: 72 }).toFile(join(root, `assets/media/${name}.webp`));
  media[name] = `require("../../assets/media/${name}.webp")`;
};
const DEST = { US: "usa", GB: "uk", AE: "uae", KR: "south-korea", ZA: "south-africa", NZ: "new-zealand", SA: "saudi-arabia", AR: "argentina", AT: "austria", BR: "brazil", CL: "chile", CO: "colombia", HR: "croatia", CZ: "czechia", DK: "denmark", EG: "egypt", FR: "france", DE: "germany", GR: "greece", IS: "iceland", IN: "india", ID: "indonesia", IE: "ireland", IT: "italy", JP: "japan", MY: "malaysia", MX: "mexico", NL: "netherlands", NO: "norway", PH: "philippines", PT: "portugal", QA: "qatar", SG: "singapore", ES: "spain", CH: "switzerland", TH: "thailand", TN: "tunisia", TR: "turkey", VN: "vietnam" };
for (const [iso, slug] of Object.entries(DEST)) await add(`dest-${iso.toLowerCase()}`, `dest-${slug}-16x9-1200.webp`);
await add("dest-ma", "morocco-blue-medina-16x9-1200.webp");
for (const r of ["europe", "asia", "africa", "middle-east", "north-america", "latin-america", "oceania"]) await add(`region-${r}`, `region-${r}-16x9-1200.webp`, 800);
await add("global", "brand-earth-network-21x9-1200.webp", 1000);
await add("hero-earth", "earth-sunrise-orbit-21x9-1200.webp", 1200);
writeFileSync(join(root, "src/lib/media.generated.ts"),
  "// Generated by scripts/prepare-assets.mjs from Higgsfield imagery (illustrative). Do not edit.\n/* eslint-disable */\nexport const MEDIA: Record<string, number> = {\n" +
  Object.entries(media).map(([k, v]) => `  "${k}": ${v},`).join("\n") + "\n};\n");

// 3. Icon + splash
const symbol = (orbit) => `
  <defs><linearGradient id="p" x1="6" y1="5" x2="26" y2="27" gradientUnits="userSpaceOnUse">
    <stop offset="0" stop-color="#39C6FF"/><stop offset="0.55" stop-color="#0057FF"/><stop offset="1" stop-color="#0A1E3F"/></linearGradient></defs>
  <circle cx="16" cy="16" r="11" fill="url(#p)"/>
  <path d="M3.2 21.5C1.6 18.4 7.4 12.2 16.2 8.1 25 4 31.4 4 30.3 7.6" fill="none" stroke="${orbit}" stroke-width="1.7" stroke-linecap="round"/>
  <path d="M30.3 7.6c-1 3.3-6.9 8.6-14.6 12.2C8.5 23.2 4.4 23.6 3.2 21.5" fill="none" stroke="${orbit}" stroke-opacity="0.35" stroke-width="1.7" stroke-linecap="round"/>
  <circle cx="23.9" cy="6.1" r="2.3" fill="${orbit}"/><circle cx="23.9" cy="6.1" r="4" fill="#39C6FF" fill-opacity="0.25"/>`;
const icon = `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <defs><radialGradient id="bg" cx="0.3" cy="0.2" r="1"><stop offset="0" stop-color="#0A2A6B"/><stop offset="1" stop-color="#020B1F"/></radialGradient></defs>
  <rect width="1024" height="1024" fill="url(#bg)"/>
  <g transform="translate(192 192) scale(20)">${symbol("#F4F8FF")}</g></svg>`;
await sharp(Buffer.from(icon)).png().toFile(join(root, "assets/icon.png"));
const fg = `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024"><g transform="translate(272 272) scale(15)">${symbol("#F4F8FF")}</g></svg>`;
await sharp(Buffer.from(fg)).png().toFile(join(root, "assets/android-icon-foreground.png"));
await sharp({ create: { width: 1024, height: 1024, channels: 4, background: "#06152E" } }).png().toFile(join(root, "assets/android-icon-background.png"));
const mono = `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024"><g transform="translate(272 272) scale(15)"><circle cx="16" cy="16" r="11" fill="#000"/><circle cx="23.9" cy="6.1" r="2.3" fill="#000"/></g></svg>`;
await sharp(Buffer.from(mono)).png().toFile(join(root, "assets/android-icon-monochrome.png"));
const splash = `<svg xmlns="http://www.w3.org/2000/svg" width="400" height="400" viewBox="0 0 32 32">${symbol("#0057FF")}</svg>`;
await sharp(Buffer.from(splash)).png().toFile(join(root, "assets/splash-icon.png"));
await sharp(Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="48" height="48" viewBox="0 0 32 32">${symbol("#0057FF")}</svg>`)).png().toFile(join(root, "assets/favicon.png"));
console.log("flags", have.length, "media", Object.keys(media).length);
